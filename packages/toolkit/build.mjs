// Bundles the CLI into one dependency-free ESM file for npm (dist/cli.mjs) and for the plugin
// both plugins (plugins/{claude,codex}/dist/actord.mjs). Tests run against the shipped builds.
import { chmodSync, copyFileSync, mkdirSync, lstatSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { build } from "esbuild";
import { EFFECT_PATTERNS } from "./src/patterns.ts";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = JSON.parse(readFileSync(join(here, "package.json"), "utf8"));

// Start from nothing so a clean checkout and this tree produce identical bytes.
rmSync(join(here, "dist"), { recursive: true, force: true });
await build({
  entryPoints: [join(here, "src/cli/bin.ts")],
  outfile: join(here, "dist/cli.mjs"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  banner: { js: "#!/usr/bin/env node" },
  define: { __ACTORD_VERSION__: JSON.stringify(pkg.version) },
  legalComments: "none",
  logLevel: "warning",
});
// esbuild doesn't set the executable bit; the bin (and the tarball's header for it) must not depend on umask.
chmodSync(join(here, "dist/cli.mjs"), 0o755);
// Library entry points for projects: plain ESM (Node won't strip types under node_modules) plus .d.ts.
const library = { outdir: join(here, "dist"), outExtension: { ".js": ".mjs" }, bundle: true, format: "esm", target: "es2022", legalComments: "none", logLevel: "warning" };
// The Agents SDK is a peer dependency: the runtime composes the project's own copy of Lifecycle.
await build({ ...library, entryPoints: { system: join(here, "src/system.ts"), runtime: join(here, "src/runtime/index.ts") }, platform: "neutral", external: ["agents", "agents/*"] });
await build({ ...library, entryPoints: { testing: join(here, "src/testing.ts") }, platform: "neutral", external: ["cloudflare:test", "agents", "agents/*"] });
// The Worker's source handlers deliver through the runtime, so the same packages stay the project's own.
await build({ ...library, entryPoints: { sources: join(here, "src/sources/index.ts") }, platform: "neutral", external: ["agents", "agents/*", "cloudflare:workers"] });
await build({ ...library, entryPoints: { vitest: join(here, "src/vitest.ts") }, platform: "node" });
execFileSync("npx", ["--no-install", "tsc", "-p", join(here, "tsconfig.build.json")], { cwd: here, stdio: "inherit" });
// Declarations keep the source's relative ".ts" specifiers; projects resolve ".js" to ".d.ts" reliably.
for (const file of readdirSync(join(here, "dist/types"), { recursive: true })) {
  if (!String(file).endsWith(".d.ts")) continue;
  const path = join(here, "dist/types", String(file));
  writeFileSync(path, readFileSync(path, "utf8").replace(/(from\s+["']\.{1,2}\/[^"']+)\.ts(["'])/g, "$1.js$2"));
}
// The reference apps have one source: root examples/. Ship template data only with Codex so a
// cached Codex plugin can scaffold them without a checkout or maintained example copies.
const templates = {};
for (const name of ["release-radar", "briefing-desk"]) {
  const source = join(here, "..", "..", "examples", name);
  templates[name] = Object.fromEntries(readdirSync(source, { recursive: true }).map(String).sort()
    .filter((f) => !/(^|\/)(node_modules|\.actord|\.wrangler|\.claude|CLAUDE\.md|\.DS_Store|worker-configuration\.d\.ts|package-lock\.json|\.env[^/]*|\.dev.vars[^/]*)(\/|$)/.test(f))
    .filter((f) => lstatSync(join(source, f)).isFile())
    .map((f) => [f, readFileSync(join(source, f), "utf8")]));
}
const codexDist = join(here, "..", "..", "plugins", "codex", "dist");
mkdirSync(codexDist, { recursive: true });
writeFileSync(join(codexDist, "reference-templates.json"), JSON.stringify(templates, null, 2) + "\n");
copyFileSync(join(here, "../../LICENSE"), join(here, "dist/LICENSE"));
copyFileSync(join(here, "../../NOTICE"), join(here, "dist/NOTICE"));
// The Room's effect guard matches the same table in-process (a node process per Bash call would cost
// every session), so it gets a generated copy; `actord guard` makes the decision once one matches.
const patterns = EFFECT_PATTERNS.map((p) => ({ id: p.id, kind: p.kind, description: p.description, source: p.regex.source, flags: p.regex.flags }));
writeFileSync(
  join(here, "..", "..", "plugins", "claude", "hooks", "effect-patterns.ts"),
  `// Generated by packages/toolkit/build.mjs from packages/toolkit/src/patterns.ts. Do not edit.\n` +
    `export type EffectPatternSource = { id: string; kind: string; description: string; source: string; flags: string }\n\n` +
    `export const EFFECT_PATTERNS: readonly EffectPatternSource[] = ${JSON.stringify(patterns, null, 2)}\n`,
);
for (const host of ["claude", "codex"]) {
  const dist = join(here, "..", "..", "plugins", host, "dist");
  mkdirSync(dist, { recursive: true });
  for (const file of readdirSync(dist)) if (file.endsWith(".tgz")) rmSync(join(dist, file));
  copyFileSync(join(here, "dist/cli.mjs"), join(dist, "actord.mjs"));
  chmodSync(join(dist, "actord.mjs"), 0o755);
  writeFileSync(join(dist, "VERSION"), `${pkg.version}\n`);
  execFileSync("npm", ["pack", "--silent", "--pack-destination", dist], { cwd: here, stdio: ["ignore", "ignore", "inherit"] });
}
console.log(`built @actord/toolkit ${pkg.version} → dist/cli.mjs, plugins/{claude,codex}/dist/actord.mjs`);
