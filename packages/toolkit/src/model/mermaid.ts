// The topology as a Mermaid flowchart, for documents that draw Mermaid (GitHub, Obsidian, many wikis).
// Deterministic: the manifest's order, and node ids derived from names with a prefix, so no actor name can
// collide with a Mermaid keyword such as `end`.
import { scheduleLabel, type Manifest } from "./manifest.ts";

const id = (name: string) => (name.startsWith("@") ? `x_${name.slice(1)}` : `a_${name}`).replace(/[^A-Za-z0-9_]/g, "_");
// Inside a quoted label Mermaid reads entity codes; a double quote would end the label.
const label = (s: string) => s.replace(/&/g, "#amp;").replace(/"/g, "#quot;").replace(/</g, "#lt;").replace(/>/g, "#gt;");

const effectId = (name: string) => `e_${name}`.replace(/[^A-Za-z0-9_]/g, "_");

export function renderMermaid(m: Manifest): string {
  const version = new Map(m.messages.map((x) => [x.name, x.version]));
  const external = [...new Set(m.routes.map((r) => r.from).filter((f) => f.startsWith("@")))].sort();
  // Routes between the same two nodes share one arrow, their messages stacked: renderers overlap the labels
  // of parallel edges and of several self-loops.
  const arrows = new Map<string, { from: string; to: string; messages: string[] }>();
  for (const r of m.routes) {
    const key = `${r.from}\0${r.to}`;
    const arrow = arrows.get(key) ?? { from: r.from, to: r.to, messages: [] };
    arrow.messages.push(label(`${r.message}@${version.get(r.message) ?? "?"}`));
    arrows.set(key, arrow);
  }
  // Only the effects an agent calls as tools get a node; other effects stay off the graph.
  const effectNames = new Set(m.effects.map((e) => e.name));
  const toolEffects = [...new Set(m.actors.flatMap((a) => (a.kind === "agent" ? (a.tools ?? []).filter((t) => effectNames.has(t)) : [])))].sort();
  const lines = [
    "flowchart LR",
    `  %% ${m.system.name}: ${m.actors.length} actor(s), ${m.routes.length} route(s). Generated by actord graph --format mermaid.`,
    ...external.map((e) => `  ${id(e)}(["${label(e)}"])`),
    ...m.actors.map((a) => {
      const text = `${label(a.name)}<br/>${label([a.kind, a.schedules.length ? a.schedules.map(scheduleLabel).join(" · ") : null].filter(Boolean).join(" · "))}`;
      return a.kind === "agent" ? `  ${id(a.name)}{{"${text}"}}` : `  ${id(a.name)}["${text}"]`;
    }),
    ...toolEffects.map((e) => `  ${effectId(e)}(["${label(e)}"])`),
    ...[...arrows.values()].map((a) => `  ${id(a.from)} -->|"${a.messages.join("<br/>")}"| ${id(a.to)}`),
    ...m.actors.flatMap((a) => (a.kind === "agent" ? (a.tools ?? []).filter((t) => effectNames.has(t)).map((t) => `  ${id(a.name)} -.-> ${effectId(t)}`) : [])),
  ];
  return lines.join("\n");
}
